import { useMemo, useState } from 'react';
import { useAppData } from '@/hooks/useappdata';
import { runFullPipeline } from '@/agents/orchestration-agent';
import { saveRecommendations, setTargetCareer } from '@/library/userdata';
import { Card, ProgressBar, Badge, SectionTitle } from '@/components/ui';
import { Briefcase, Target, ChevronDown, ChevronUp, Check, Sparkles, AlertCircle } from 'lucide-react';

export function CareersPage() {
  const { loading, error, profile, careers, careerSkillsByCareer, trends, userSkills, projects, certifications, progress, reload } = useAppData();
  const [expanded, setExpanded] = useState<string | null>(null);
  const [saving, setSaving] = useState(false);

  const result = useMemo(() => {
    if (!profile || careers.length === 0) return null;
    return runFullPipeline(
      { profile, userSkills, projects, certifications, careers, careerSkillsByCareer, trends, learningResources: [], progress },
      profile.target_career_id,
    );
  }, [profile, careers, careerSkillsByCareer, trends, userSkills, projects, certifications, progress]);

  const handleSelectCareer = async (careerId: string) => {
    if (!profile) return;
    setSaving(true);
    try {
      await setTargetCareer(profile.id, careerId);
      await reload();
    } finally {
      setSaving(false);
    }
  };

  const handleRunAgents = async () => {
    if (!profile || !result) return;
    setSaving(true);
    try {
      await saveRecommendations(
        profile.id,
        result.careerRecommendations.map((r) => ({
          career_id: r.career.id,
          compatibility_score: r.compatibility_score,
          skill_match: r.skill_match,
          interest_match: r.interest_match,
          education_match: r.education_match,
          experience_match: r.experience_match,
          industry_demand: r.industry_demand,
          explanation: r.explanation,
        })),
      );
      await reload();
    } finally {
      setSaving(false);
    }
  };

  if (loading) return <div className="py-20 text-center text-slate-400">Loading recommendations...</div>;
  if (error) return <Card className="p-6 text-rose-600 flex items-center gap-2"><AlertCircle className="w-5 h-5" />{error}</Card>;
  if (!profile || !profile.full_name)
    return <Card className="p-8 text-center"><p className="text-slate-500">Please complete your profile first to get career recommendations.</p></Card>;
  if (!result) return null;

  return (
    <div>
      <SectionTitle
        title="Career Recommendations"
        subtitle="Generated by the Career Recommendation Agent using a weighted scoring model"
        icon={<Briefcase className="w-5 h-5" />}
      />

      {/* Scoring formula explanation */}
      <Card className="p-5 mb-6 bg-teal-50/50 border-teal-100">
        <div className="flex items-start gap-3">
          <Sparkles className="w-5 h-5 text-teal-600 flex-shrink-0 mt-0.5" />
          <div className="text-sm text-slate-600">
            <strong className="text-slate-800">How scores are calculated:</strong> Each career is scored on five factors —
            Skill Match (40%), Interest Match (20%), Education Match (15%), Experience Match (15%), and Industry Demand (10%).
            The weighted sum produces the compatibility score you see below.
          </div>
        </div>
        <button
          onClick={handleRunAgents}
          disabled={saving}
          className="mt-3 px-4 py-2 rounded-lg bg-teal-600 text-white text-sm font-medium hover:bg-teal-700 transition-all disabled:opacity-50"
        >
          {saving ? 'Running agents...' : 'Re-run Career Agent'}
        </button>
      </Card>

      <div className="space-y-4">
        {result.careerRecommendations.map((rec, i) => {
          const isExpanded = expanded === rec.career.id;
          const isTarget = profile.target_career_id === rec.career.id;
          return (
            <Card key={rec.career.id} className={`overflow-hidden transition-all ${isTarget ? 'ring-2 ring-teal-400' : ''}`}>
              <div className="p-5">
                <div className="flex items-start gap-4">
                  <div className="flex-shrink-0 w-10 h-10 rounded-xl bg-slate-100 text-slate-600 flex items-center justify-center font-bold">
                    {i + 1}
                  </div>
                  <div className="flex-1 min-w-0">
                    <div className="flex items-center gap-2 flex-wrap">
                      <h3 className="text-lg font-bold text-slate-800">{rec.career.name}</h3>
                      {isTarget && <Badge color="teal"><Target className="w-3 h-3 mr-1" />Selected</Badge>}
                      <Badge>{rec.career.domain}</Badge>
                    </div>
                    <p className="text-sm text-slate-500 mt-1">{rec.career.description}</p>

                    <div className="mt-3 flex items-center gap-4">
                      <div className="flex-1">
                        <ProgressBar value={rec.compatibility_score} label="Compatibility" showValue color="bg-teal-500" />
                      </div>
                      <button
                        onClick={() => setExpanded(isExpanded ? null : rec.career.id)}
                        className="text-sm text-teal-600 font-medium flex items-center gap-1 flex-shrink-0"
                      >
                        {isExpanded ? 'Hide' : 'Details'}
                        {isExpanded ? <ChevronUp className="w-4 h-4" /> : <ChevronDown className="w-4 h-4" />}
                      </button>
                    </div>
                  </div>
                </div>

                {isExpanded && (
                  <div className="mt-4 pt-4 border-t border-slate-100 ml-14">
                    <p className="text-sm text-slate-600 mb-4 italic">{rec.explanation}</p>
                    <div className="grid grid-cols-2 md:grid-cols-5 gap-3 mb-4">
                      {[
                        { label: 'Skill Match', value: rec.skill_match },
                        { label: 'Interest Match', value: rec.interest_match },
                        { label: 'Education', value: rec.education_match },
                        { label: 'Experience', value: rec.experience_match },
                        { label: 'Industry Demand', value: rec.industry_demand },
                      ].map((f) => (
                        <div key={f.label} className="text-center p-3 rounded-xl bg-slate-50">
                          <div className="text-xl font-bold text-slate-700">{f.value}%</div>
                          <div className="text-xs text-slate-400 mt-0.5">{f.label}</div>
                        </div>
                      ))}
                    </div>
                    <div className="mb-4">
                      <div className="text-sm font-medium text-slate-600 mb-2">Required Skills</div>
                      <div className="flex flex-wrap gap-2">
                        {(careerSkillsByCareer[rec.career.id] ?? []).map((cs) => (
                          <span
                            key={cs.skill_id}
                            className={`px-2.5 py-1 rounded-lg text-xs font-medium border ${
                              cs.priority === 'high'
                                ? 'bg-rose-50 text-rose-600 border-rose-100'
                                : cs.priority === 'medium'
                                ? 'bg-amber-50 text-amber-600 border-amber-100'
                                : 'bg-slate-50 text-slate-500 border-slate-100'
                            }`}
                          >
                            {cs.skill?.name}
                          </span>
                        ))}
                      </div>
                    </div>
                    {!isTarget && (
                      <button
                        onClick={() => handleSelectCareer(rec.career.id)}
                        disabled={saving}
                        className="px-5 py-2.5 rounded-xl bg-teal-600 text-white font-medium text-sm hover:bg-teal-700 transition-all flex items-center gap-2"
                      >
                        <Check className="w-4 h-4" /> Set as Target Career
                      </button>
                    )}
                  </div>
                )}
              </div>
            </Card>
          );
        })}
      </div>
    </div>
  );
}